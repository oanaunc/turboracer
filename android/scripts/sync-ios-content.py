#!/usr/bin/env python3
"""Derive the Android catalogue and story verbatim from the shipping Swift source."""
import json,pathlib,re,sys,hashlib
root=pathlib.Path(__file__).resolve().parents[2]
world=(root/'Afterlight/Sources/World.swift').read_text();app=(root/'Afterlight/Sources/AfterlightApp.swift').read_text()
cars=[]
for row in re.findall(r'Car\(id: (.*?)\)(?:,|\n)',world):
    def val(key,default=None):
        m=re.search(r'\b'+key+r': ("[^"]*"|0x[\dA-Fa-f]+|[\d.]+|\.[a-z]+)',row)
        if not m:return default
        v=m[1]
        return json.loads(v) if v.startswith('"') else v[1:] if v.startswith('.') else int(v,16) if v.startswith('0x') else float(v) if '.' in v else int(v)
    c={k:val(k) for k in ['name','subtitle','price','speed','handling','color','design','carClass']};c['id']=int(row.split(',')[0]);c['kit']=val('kit',0);c['finish']=val('finish','metallic');cars.append(c)
circuits=[]
for m in re.finditer(r'Circuit\((\d+),"([^"]+)","([^"]+)",(\d+),(\d+),\[(.*?)\]\)',world):
    circuits.append(dict(id=int(m[1]),name=m[2],tagline=m[3],environment=int(m[4]),route=int(m[5]),coordinates=[[float(a),float(b)] for a,b in re.findall(r'\((-?[\d.]+),(-?[\d.]+)\)',m[6])]))
def strings(fragment):return re.findall(r'"((?:[^"\\]|\\.)*)"',fragment)
def method_array(name):
    m=re.search(r'func '+name+r'\(_ id:Int\) -> String \{ \[(.*?)\]\[id\]',app)
    return [s.replace('\\"','"') for s in strings(m[1])]
looks=(root/'Afterlight/Sources/RouteScenery.swift').read_text()
settings=re.findall(r'\.init\(setting:"([^"]+)"',looks)
for c in circuits:c['setting']=settings[c['id']]
content=dict(cars=cars,circuits=circuits,story=method_array('story'),notebook=method_array('notebook'),quotes=["“Speed is easy. A clean line takes heart.”","“The lights don't make the city. The people do.”","“Out here, patience is faster than pride.”","“Your father left a road. You get to choose where it leads.”"],intro="You inherited a shuttered garage and your father's Solstice. Mika, your oldest friend and mechanic, has a plan: enter the Afterlight Festival, win back the garage's reputation, and reach the summit race your father never finished.")
assert len(cars)==12 and len(circuits)==20 and len(content['story'])==4 and len(content['notebook'])==4
result='// Generated by scripts/sync-ios-content.py. Edit the Swift catalogue.\nexport default '+json.dumps(content,ensure_ascii=False,indent=2)+';\n'
file=root/'android/web/content.js'
if '--check' in sys.argv:
    if not file.exists() or file.read_text()!=result:raise SystemExit('Android content is stale. Run sync-ios-content.py.')
else:file.write_text(result)
print('Verified 12 cars, 20 circuits, 80 events and all four story/notebook chapters against Swift.')
